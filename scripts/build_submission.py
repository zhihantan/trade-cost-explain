"""Assemble the FE Bar build-submission folder: a curated subset of this repository that fits the validator's reading
limits (30 files, 9,000 characters per file, 90,000 in total), so the evidence is read instead of being cut off.

    python scripts/build_submission.py [--out submission] [--deny-file .private/deny_terms.txt]

Checks the file count, per-file truncation, total size, upload keep-list extensions, secrets, optional deny terms
(one per line, kept out of Git) and that every layer has a code construct in the folder. Exits 1 on any failure.
"""
from __future__ import annotations

import argparse
import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MARKER = ".generated"

# Narrative and evidence first, then the files that show each layer.
MANIFEST = [
    "README.md",
    "BUILD.md",
    "evidence/README.md",
    "evidence/00_local_checks.md",
    "evidence/01_lakeflow_pipeline_tie_out.md",
    "evidence/02_unity_catalog_row_filters.md",
    "evidence/03_lakebase_review_loop.md",
    "evidence/04_genai_agent_and_extraction.md",
    "evidence/05_genie_benchmarks.md",
    "evidence/06_app_smoke_test.md",
    # Lakeflow
    "resources/ce_medallion.pipeline.yml",
    "src/pipeline/bronze/trades_raw.sql",
    "src/pipeline/silver/trades.sql",
    "src/pipeline/gold/cost_flux_bridge.sql",
    # Unity Catalog
    "src/governance/row_filters.sql",
    "src/governance/grants.sql",
    # Lakebase
    "resources/cost_explain_db.postgres_project.yml",
    "cost-explain-app/backend/db_lakebase.py",
    # Gen AI
    "src/agent/commentary_agent.py",
    # Genie
    "resources/cost_explain.genie_space.yml",
    "src/genie/ask.py",
    # App
    "cost-explain-app/app.yaml",
    "cost-explain-app/backend/main.py",
]

MAX_FILES, MAX_PER_FILE, MAX_TOTAL = 30, 9_000, 90_000
# Worst case (SKNAV-707): README.md and BUILD.md are pinned on top of the ranked files, plus a file listing.
PINNED, LISTING_ALLOWANCE = ("README.md", "BUILD.md"), 2_000
# What the submission form's folder reader keeps; .log/.out/.jsonl and binaries are dropped before upload.
KEEP_EXT = {".py", ".ipynb", ".sql", ".md", ".txt", ".json", ".csv", ".yaml", ".yml", ".ts", ".tsx", ".js", ".jsx", ".sh"}
PROSE_EXT = {".md", ".txt", ".csv"}
# Our approximation of the validator's layer scan, matched in code files only (prose does not count).
LAYERS = {
    "Lakeflow": r"STREAMING TABLE|MATERIALIZED VIEW|read_files|cloudFiles|^\s*pipelines:",
    "Unity Catalog": r"ROW FILTER|\bGRANT\b|CREATE (OR REPLACE )?FUNCTION",
    "Lakebase": r"postgres_projects:|generate_database_credential|psycopg",
    "ML / Gen AI": r"ResponsesAgent|mlflow|serving_endpoints",
    "Genie": r"genie_spaces:|/api/2\.0/genie/",
    "App": r"^\s*apps:|from fastapi|uvicorn",
}
SECRET = re.compile(r"dapi[0-9a-f]{32}|gh[pousr]_[A-Za-z0-9]{30,}|github_pat_|sk-[A-Za-z0-9-]{20,}|AKIA[0-9A-Z]{16}"
                    r"|xox[abprs]-|BEGIN [A-Z ]*PRIVATE KEY")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="submission")
    ap.add_argument("--deny-file", default=".private/deny_terms.txt")
    a = ap.parse_args()

    out = (ROOT / a.out).resolve()
    if ROOT not in out.parents:
        sys.exit(f"--out must be inside {ROOT}")
    if out.exists():
        if not (out / MARKER).exists():
            sys.exit(f"{out} exists and was not created by this script; not touching it")
        shutil.rmtree(out)

    deny_path = ROOT / a.deny_file
    deny = [t.strip() for t in deny_path.read_text().splitlines() if t.strip()] if deny_path.exists() else []
    deny_rx = re.compile("|".join(map(re.escape, deny)), re.I) if deny else None

    failures, rows, total, texts = [], [], 0, {}
    if len(MANIFEST) > MAX_FILES:
        failures.append(f"{len(MANIFEST)} files > {MAX_FILES}")
    for rel in MANIFEST:
        src = ROOT / rel
        if not src.exists():
            failures.append(f"missing: {rel}")
            continue
        text = src.read_text(encoding="utf-8")
        texts[rel] = text
        read = min(len(text), MAX_PER_FILE)
        total += read
        note = f"read {MAX_PER_FILE:,} of {len(text):,}" if len(text) > MAX_PER_FILE else ""
        if src.suffix not in KEEP_EXT:
            failures.append(f"dropped by the upload filter: {rel}")
        if SECRET.search(text):
            failures.append(f"secret-like string: {rel}")
        if deny_rx and deny_rx.search(text):
            failures.append(f"deny term in: {rel}")
        rows.append((rel, len(text), note))
        (out / rel).parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(src, out / rel)
    (out / MARKER).write_text("Generated by scripts/build_submission.py; safe to delete.\n")

    worst = total + sum(min(len(texts.get(r, "")), MAX_PER_FILE) for r in PINNED) + LISTING_ALLOWANCE
    if worst > MAX_TOTAL:
        failures.append(f"worst case {worst:,} characters > {MAX_TOTAL:,}; drop or shorten a file")
    code = "\n".join(t for r, t in texts.items() if Path(r).suffix not in PROSE_EXT)
    layers = {name: bool(re.search(rx, code, re.M)) for name, rx in LAYERS.items()}
    failures += [f"no code construct for layer: {n}" for n, ok in layers.items() if not ok]

    for rel, size, note in rows:
        print(f"{size:>7,}  {rel}  {note}")
    print(f"\n{len(rows)} files · {total:,} characters read · worst case with pinned files {worst:,} of "
          f"{MAX_TOTAL:,} ({MAX_TOTAL - worst:,} to spare) · "
          f"deny terms: {len(deny) or 'none loaded'}")
    print("layers: " + " · ".join(f"{n} {'ok' if ok else 'MISSING'}" for n, ok in layers.items()))
    print(f"folder: {out}")
    for f in failures:
        print(f"FAIL  {f}")
    print("RESULT: " + ("FAIL" if failures else "PASS"))
    return 1 if failures else 0


if __name__ == "__main__":
    sys.exit(main())
